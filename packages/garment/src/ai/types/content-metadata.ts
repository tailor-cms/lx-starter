/**
 * Content Metadata Types
 * AI-generated semantic metadata for repositories
 * Used by: MetadataGenerator, ContentAnalyzer
 */
import type { BloomLevel, DifficultyLevel, TagCategory } from './taxonomies';

/**
 * Real-world problem that learners can solve after completing content
 * LLM-generated practical application scenarios
 */
export interface Problem {
  // Unique problem identifier
  id: string;
  // Problem title or scenario name
  title: string;
  // Detailed problem description and context
  description: string;
  // Business domain or industry category
  // Example: 'web-development', 'data-analysis', 'business'
  category: string;
  // Problem difficulty level
  difficulty: DifficultyLevel;
  // Skills required to solve this problem
  // Example: ['javascript', 'async-programming', 'error-handling']
  requiredSkills: string[];
  // Estimated time to solve in minutes
  estimatedTime: number;
  // uids where this problem's concepts are taught
  // Used for precise navigation to relevant content sections
  sectionIds?: string[];
}

/**
 * Content tag with weight and hierarchy
 * LLM-generated topic tags for content classification and search
 */
export interface Tag {
  // Tag name (e.g., 'async-await', 'promises', 'javascript')
  name: string;
  // Tag category for organization
  category: TagCategory;
  // Importance weight in content (0-1)
  // Higher values indicate more prominent topics
  // Example: 0.9 for primary topic, 0.3 for briefly mentioned
  weight: number;
  // Parent tag name for hierarchical organization
  // Example: 'promises' might have parent 'async-programming'
  parent?: string;
  // uids where this tag was identified
  // Used for traceability and section-specific recommendations
  sectionIds?: string[];
}

/**
 * Learning outcome or objective
 * LLM-generated learning goals aligned with Bloom's taxonomy
 */
export interface LearningOutcome {
  // Unique outcome identifier
  id: string;
  // Clear, specific learning objective description
  // Example: "Apply async/await patterns to handle asynchronous operations"
  description: string;
  // Bloom's taxonomy cognitive level
  // Indicates depth of learning (remember → create)
  bloomLevel: BloomLevel;
  // Whether the outcome is measurable and observable
  // True if learner achievement can be demonstrated/assessed
  measurable: boolean;
  // Specific criteria for assessing achievement
  // Example: ["Can write async functions", "Can handle errors with try-catch"]
  assessmentCriteria?: string[];
  // uids where this outcome is addressed or achieved
  // Used for precise navigation to relevant content sections
  sectionIds?: string[];
}

/**
 * Prerequisite knowledge or skill
 * Required background knowledge for understanding content
 */
export interface Prerequisite {
  // Tag name representing the prerequisite concept
  // Example: 'javascript-basics', 'html-fundamentals'
  tag: string;
  // Optional tag category
  category?: TagCategory;
  // Importance level (0-1)
  // 1.0 = essential prerequisite, 0.3 = helpful but not critical
  importance: number;
  // Optional explanation of why this prerequisite is needed
  description?: string;
}

/**
 * Complete AI-generated metadata for a repository
 * Comprehensive semantic metadata generated by LLM from content analysis
 */
export interface ContentMeta {
  // Repository unique identifier
  id: string;
  // Repository name or title
  name: string;

  // ============================================================================
  // CLASSIFICATION
  // ============================================================================
  // Real-world problems learners can solve after completing content
  // Generated by LLM to demonstrate practical application
  problems: Problem[];
  // Content topic tags with weights
  // Used for search, recommendations, and content discovery
  tags: Tag[];
  // Overall difficulty level of the content
  difficulty: DifficultyLevel;

  // ============================================================================
  // LEARNING DESIGN
  // ============================================================================
  // Learning outcomes aligned with Bloom's taxonomy
  // What learners will be able to do after completing content
  learningOutcomes: LearningOutcome[];
  // Required prerequisite knowledge
  // Background knowledge needed before starting this content
  prerequisites: Prerequisite[];
  // Estimated time to complete in minutes
  estimatedDuration: number;

  // ============================================================================
  // CONTENT ANALYSIS METRICS
  // ============================================================================
  // Content complexity score (0-1)
  // Based on vocabulary, structure, and depth
  contentComplexity: number;
  // Practical vs theoretical focus (0-1)
  // 0 = purely theoretical, 1 = purely practical/hands-on
  practicalFocus: number;
  // Interactivity level (0-1)
  // Based on exercises, examples, and interactive elements
  interactivityLevel: number;

  // ============================================================================
  // METADATA TRACKING
  // ============================================================================
  // Timestamp when metadata was generated
  generatedAt: Date;
  // LLM model version used for generation
  // Used for tracking and potential regeneration
  modelVersion?: string;
  // Time taken to analyze this repository in milliseconds (optional)
  // Only set during generation, undefined when loaded from storage
  // Typical range: 2000-10000ms depending on content size and LLM provider
  processingTime?: number;
}

/**
 * Metadata generator options
 * Controls LLM-based metadata generation for educational content
 */
export interface MetadataGeneratorOptions {
  // Maximum number of practice problems to generate per repository
  // Typical range: 3-10
  // Default: 5
  maxProblems?: number;
  // Maximum number of topic tags to generate per repository
  // Typical range: 3-15
  // Default: 10
  maxTags?: number;
  // Maximum number of learning outcomes to generate per repository
  // Typical range: 2-8
  // Default: 5
  maxOutcomes?: number;
  // Number of concurrent LLM API requests to allow
  // Higher values speed up batch processing but increase costs
  // Default: 3
  concurrency?: number;
}
